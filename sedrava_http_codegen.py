"""Generate a CSP-compatible browser adapter for a declared read-only JSON API.

The adapter is a standalone JS module; integration into .sdr UI remains pending.
"""
import json
from sedrava_http import ApiService, JsonResponse


def generate_fetch_module(service: ApiService, schema: JsonResponse) -> str:
    if type(service) is not ApiService or type(schema) is not JsonResponse:
        raise ValueError("Expected validated service and JSON response schema")
    config = {
        "url": service.url,
        "timeout": service.timeout_ms,
        "maxBytes": service.max_bytes,
        "many": schema.many,
        "maxItems": schema.max_items,
        "fields": [{"name": f.name, "kind": f.kind} for f in schema.fields],
    }
    # Encode '<' to prevent accidental HTML script termination if embedded elsewhere.
    serialized = json.dumps(config, ensure_ascii=True, separators=(",", ":")).replace("<", "\\u003c")
    return """// Generated by Sedrava; read-only HTTP connector.
const CONFIG = """ + serialized + """;
export async function load({ signal } = {}) {
  const controller = new AbortController();
  const timeout = setTimeout(() => controller.abort(), CONFIG.timeout);
  const abort = () => controller.abort();
  if (signal) {
    if (signal.aborted) controller.abort();
    else signal.addEventListener('abort', abort, { once: true });
  }
  try {
    const response = await fetch(CONFIG.url, {
      method: 'GET', credentials: 'omit', redirect: 'error',
      cache: 'no-store', signal: controller.signal,
      headers: { Accept: 'application/json' }
    });
    if (!response.ok) throw new Error('HTTP status ' + response.status);
    const type = response.headers.get('content-type') || '';
    if (!/^application\\/json(?:\\s*;|$)/i.test(type)) throw new Error('Expected JSON response');
    const reader = response.body?.getReader();
    if (!reader) throw new Error('Streaming response required');
    const chunks = []; let length = 0;
    while (true) {
      const {done, value} = await reader.read();
      if (done) break;
      length += value.byteLength;
      if (length > CONFIG.maxBytes) {
        await reader.cancel();
        throw new Error('Response exceeds configured byte limit');
      }
      chunks.push(value);
    }
    const bytes = new Uint8Array(length); let offset = 0;
    for (const chunk of chunks) { bytes.set(chunk, offset); offset += chunk.length; }
    const data = JSON.parse(new TextDecoder('utf-8', {fatal:true}).decode(bytes));
    const rows = CONFIG.many ? data : [data];
    if (!Array.isArray(rows) || rows.length > CONFIG.maxItems) throw new Error('Invalid collection');
    for (const row of rows) {
      if (row === null || Array.isArray(row) || typeof row !== 'object') throw new Error('Invalid record');
      const keys = Object.keys(row);
      if (keys.length !== CONFIG.fields.length) throw new Error('Unexpected fields');
      for (const field of CONFIG.fields) {
        if (!Object.prototype.hasOwnProperty.call(row, field.name)) throw new Error('Missing field');
        const v = row[field.name];
        if (field.kind === 'text' && (typeof v !== 'string' || Array.from(v).length > 1024 ||
            Array.from(v).some(c => c.codePointAt(0) < 32 && c !== '\\n' && c !== '\\t')))
          throw new Error('Invalid text field');
        if (field.kind === 'int32' && (!Number.isInteger(v) || v < -2147483648 || v > 2147483647))
          throw new Error('Invalid int32 field');
        if (field.kind === 'bool' && typeof v !== 'boolean') throw new Error('Invalid bool field');
      }
    }
    return data;
  } finally {
    clearTimeout(timeout);
    if (signal) signal.removeEventListener('abort', abort);
  }
}
"""
